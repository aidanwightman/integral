{
  const d=dataset('events'),sale=d.approvalRequests.find(r=>r.type==='sale');
  const deal=d.opportunities.find(o=>o.id===sale.targetId),reason='Annual booking commitment.';
  const gross=deal.valuePence, before=metrics(d), baseline=cashForecast(d), projected=cashForecast(d,{pipeline:true}), openingCash=d.openingCashPence;
  const ask=(percent,prior)=>requestApproval(d,'sales','discount',{targetId:deal.id,reason,discountPercent:percent,
    ...(prior?{requestId:prior.id,version:prior.history.length}:{})});
  decideApproval(d,'saleslead',sale.id,1,'approved');
  assert.match(approvalRecordPanel(d,'sales','opportunities',deal.id),/Request discount/);
  for(const invalid of ['','0','100.01','1.234','1e1','-1']) assert.throws(()=>ask(invalid),/discount/);
  const discount=ask('12.25'),decide=(version,decision,note)=>decideApproval(d,'saleslead',discount.id,version,decision,note);
  assert.equal(deal.valuePence,gross);
  assert.deepEqual(metrics(d),before);
  assert(approvalAlerts(d,'saleslead').some(a=>a.requestId===discount.id));
  assert.match(approvalView(d,{role:'saleslead',approvalFocus:discount.id}),/12.25% discount/);
  assert.throws(()=>ask('7'),/already/);
  decide(1,'denied','Adjust for volume.');
  assert.equal(deal.valuePence,gross);
  assert(approvalAlerts(d,'sales').some(a=>a.requestId===discount.id));
  ask('7.25',discount);
  assert.throws(()=>decide(1,'approved'),/changed/);
  deal.valuePence++;
  assert.throws(()=>decide(3,'approved'),/terms changed/);
  assert.equal(discount.history.length,3);
  deal.valuePence--;
  decide(3,'approved');
  const net=Math.round(gross*.9275);
  assert.equal(deal.valuePence,net);
  assert.equal(deal.pricing.grossPence,gross);
  assert.equal(deal.pricing.revision,1);
  assert.equal(saleSignoff(d,deal.id),'changed');
  assert.equal(deal.termsStatus,'New terms need sign-off');
  assert.equal(metrics(d).pipeline,before.pipeline-(gross-net));
  assert.equal(metrics(d).weighted,Math.round(d.opportunities.filter(o=>o.probability<1).reduce((n,o)=>n+o.valuePence*o.probability,0)));
  assert.equal(d.openingCashPence,openingCash);
  assert.deepEqual(cashForecast(d),baseline);
  assert(cashForecast(d,{pipeline:true})[deal.closeMonth-1].potential<projected[deal.closeMonth-1].potential);
  assert(metrics(d).weighted<before.weighted);
  assert.throws(()=>decide(3,'approved'),/changed/);
  assert.throws(()=>decide(4,'approved'),/pending/);
  assert(d.activity.some(a=>a.opportunityId===deal.id && a.action==='Deal discount approved' && a.detail.includes('7.25% discount')));
  const approved=structuredClone(discount.history[3].discount);
  ask('15',discount);
  assert.equal(deal.valuePence,net);
  assert.deepEqual(discount.history[3].discount,approved);
  assert.equal(discount.discount.grossPence,gross);
  assert.equal(discount.discount.priorPence,net);
  decide(5,'approved');
  assert.equal(deal.valuePence,Math.round(gross*.85));
  assert.equal(deal.pricing.revision,2);
  assert.throws(()=>ask('15',discount),/changes the deal/);
  assert.throws(()=>requestApproval(d,'sales','discount',{targetId:d.opportunities.find(o=>o.probability===1).id,reason,discountPercent:10}),/open deal/);

  const oldOwner=deal.owner, to=d.team.find(t=>t.department.includes('sales') && t.name!==oldOwner);
  const pass=(role,ownerId,why,ver=0,from=oldOwner)=>handoffOpportunity(d,deal.id,role,{ownerId,reason:why},ver,from);
  assert.throws(()=>pass('finance',to.id,reason),/Only the sales/);
  assert.throws(()=>pass('sales','unknown',reason),/colleague/);
  assert.throws(()=>pass('sales',to.id,' '),/note/);
  pass('sales',to.id,'Pick up procurement review on Friday.');
  assert.equal(deal.owner,to.name);
  assert.deepEqual([deal.ownerHistory[0].from,deal.ownerHistory[0].to,deal.ownerHistory[0].role],[oldOwner,to.name,'sales']);
  assert.throws(()=>pass('sales',to.id,reason),/owner changed/);
  assert.equal(deal.ownerHistory.length,1);
  assert(d.activity.some(a=>a.opportunityId===deal.id && a.accountId===deal.accountId && a.action==='Deal owner changed' && a.detail.includes('procurement')));
  assert.match(dealOwnerForm(d,deal,'saleslead'),/data-version="1"/);
  assert.equal(dealOwnerForm(d,deal,'operations'),'');
  console.log('PASS: discounted pricing, stale reviews, signed terms, reassignment history and role-scoped controls.');
}
