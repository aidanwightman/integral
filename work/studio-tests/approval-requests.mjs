  assert.throws(()=>decide(3,'approved'),/changed/);
  assert.equal(event.fields.Registered,seats+1);
  assert(!approvalAlerts(d,'saleslead').some(a=>a.requestId===r.id));
  assert.match(approvalView(d,{role:'operations',approvalFocus:r.id}),/one place allocated/);
