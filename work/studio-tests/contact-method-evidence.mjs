import assert from 'node:assert/strict';
import {dataset,INDUSTRIES} from '../../outputs/workspace-concepts/studio-src/data.js';
import {crmContactMethod,crmRecordMethodCheck,crmSaveContact,crmSendEmail,crmLogInbound} from '../../outputs/workspace-concepts/studio-src/contact-model.js';
import {recordConfirmedAddress} from '../../outputs/workspace-concepts/studio-src/address-confirmation.js';
import {startCall,endCall,logCall,logCompletedCall,saveContactEmail} from '../../outputs/workspace-concepts/studio-src/calling.js';
import {persistContactMethods,restoreContactMethods} from '../../outputs/workspace-concepts/studio-src/contact-method-session.js';

const storage = new Map();
globalThis.sessionStorage={getItem:key=>storage.get(key) || null,setItem:(key,value)=>storage.set(key,value)};
const contactEdit = contact=>({...contact,firstName:contact.name.split(' ')[0],lastName:contact.name.split(' ')[1]});
for(const industry of INDUSTRIES) {
  const d=restoreContactMethods(dataset(industry.id));
  const [sam,morgan]=d.contacts;
  const read=method=>crmContactMethod(sam,method);
  assert.equal(read('email').status,'Unverified');
  assert.equal(read('email').lastCheckedAt,null);
  assert.equal(read('phone').lastVerifiedAt,null);
  assert.equal(crmContactMethod(morgan,'email').status,'Missing');
  const old='2024-01-15T08:30:00.000Z';
  sam.emailEvidence={address:sam.email.toUpperCase(),source:'Company directory',detail:'Named entry and address',at:old};
  assert.equal(read('email').lastVerifiedAt,old);
  assert.equal(read('email').lastCheckedAt,old);

  const uncertain={method:'email',value:sam.email,result:'unconfirmed',source:'Directory',evidence:'The directory no longer lists this person.'};
  const inconclusive=crmRecordMethodCheck(d,sam.id,uncertain);
  assert.equal(inconclusive.status,'Needs review');
  assert.ok(Date.parse(inconclusive.lastCheckedAt)>Date.parse(old));
  assert.equal(inconclusive.lastVerifiedAt,old);
  assert.equal(inconclusive.verificationSource,'Company directory');
  assert.equal(inconclusive.evidence,uncertain.evidence);
  const backfilled=crmRecordMethodCheck(d,sam.id,{...uncertain,result:'verified',source:'Direct confirmation',evidence:'Read back on the original handover call.',checkedAt:'2025-02-01T09:30:00Z'});
  assert.equal(backfilled.status,'Needs review');
  assert.equal(backfilled.lastCheckedAt,inconclusive.lastCheckedAt);
  assert.equal(backfilled.evidence,uncertain.evidence);
  assert.equal(backfilled.lastVerifiedAt,'2025-02-01T09:30:00.000Z');
  assert.equal(backfilled.verificationSource,'Direct confirmation');
  assert.equal(d.salesActivity[0].checkedAt,backfilled.lastVerifiedAt);
  assert.equal(read('phone').lastCheckedAt,null);
  const email=sam.email;
  crmSendEmail(d,sam.id,{subject:'Account update',body:'Here is our account update.'});
  assert.deepEqual(read('email'),backfilled);
  saveContactEmail(d,sam.id,'Contact+new@customer.example');
  assert.equal(read('email').status,'Changed');
  assert.equal(read('email').lastCheckedAt,null);
  assert.equal(read('email').lastVerifiedAt,null);
  assert.ok(read('email').changedAt);
  const before=JSON.stringify(d);
  assert.throws(()=>crmRecordMethodCheck(d,sam.id,uncertain),/changed/);
  assert.throws(()=>crmRecordMethodCheck(d,sam.id,{...uncertain,value:sam.email,source:''}),/source/);
  assert.throws(()=>saveContactEmail(d,sam.id,sam.email,{address:email,source:'Wrong address',at:old,detail:'Mismatched record'}),/this email address/);
  assert.equal(JSON.stringify(d),before);
  sam.emailStatus='bounced';
  assert.equal(read('email').status,'Needs review');
  assert.throws(()=>crmRecordMethodCheck(d,sam.id,{...uncertain,value:sam.email,result:'verified'}),/correct/);
  delete sam.emailStatus;

  const confirmPhone={method:'phone',value:sam.phone.replace('+44','0044'),result:'verified',source:'Contact confirmation',evidence:'Sam read the number back during the meeting.'};
  const phoneProof=crmRecordMethodCheck(d,sam.id,{...confirmPhone,checkedAt:'2026-01-10T13:20:00+01:00'});
  assert.equal(phoneProof.status,'Verified');
  assert.equal(phoneProof.lastCheckedAt,phoneProof.lastVerifiedAt);
  assert.equal(phoneProof.lastCheckedAt,'2026-01-10T12:20:00.000Z');
  assert.ok(phoneProof.recordedAt>phoneProof.lastCheckedAt);
  for (const stamp of ['2040-05-01T08:35','2025-02-30T12:00']) assert.throws(()=>crmRecordMethodCheck(d,sam.id,{...confirmPhone,checkedAt:stamp}));
  const inbound={sender:sam.email,subject:'Contact details',body:'Sam, account lead, 020 1234 5678',received:old};
  crmLogInbound(d,inbound);
  const message=d.crmEmails.find(m=>m.direction==='Incoming');
  assert.throws(()=>crmRecordMethodCheck(d,sam.id,{...confirmPhone,sourceMessageId:d.crmEmails.find(m=>m.direction==='Outgoing').id}),/incoming email/);
  assert.throws(()=>crmRecordMethodCheck(d,morgan.id,{...confirmPhone,value:morgan.phone,sourceMessageId:message.id}),/incoming email/);
  const fromOlderSource=crmRecordMethodCheck(d,sam.id,{...confirmPhone,checkedAt:'2026-03-01T09:00:00Z',sourceMessageId:message.id});
  assert.equal(fromOlderSource.sourceMessageId,message.id);
  assert.equal(fromOlderSource.lastVerifiedAt,phoneProof.lastVerifiedAt);
  assert.equal(fromOlderSource.verificationMessageId,'');
  assert.equal(d.emailOutbox.length,0);
  const number=sam.phone.replaceAll(' ','');
  crmSaveContact(d,{...contactEdit(sam),phone:number},{editingId:sam.id});
  assert.equal(read('phone').lastVerifiedAt,phoneProof.lastVerifiedAt);
  const same=sam.phone;
  const call=startCall(d,sam.id);endCall(d,call.id);
  logCall(d,call.id,{outcome:'Wrong number',notes:'Another person answered.'});
  assert.equal(read('phone').status,'Needs review');
  assert.equal(read('phone').lastCheckedAt,call.endedAt);
  assert.equal(read('phone').lastVerifiedAt,phoneProof.lastVerifiedAt);
  crmSaveContact(d,{...contactEdit(sam),phone:'+44 7700 911111',originalPhone:same},{editingId:sam.id});
  assert.equal(read('phone').status,'Changed');
  assert.equal(read('phone').lastVerifiedAt,null);
  assert.throws(()=>crmSaveContact(d,{...contactEdit(sam),originalPhone:same},{editingId:sam.id}),/number changed/);
  assert.equal(sam.callAllowed,false);

  // The act of recording historical evidence now is separate from when the contact actually confirmed it.
  const {call:historic}=logCompletedCall(d,{contactId:morgan.id,ownerId:morgan.ownerId,direction:'Inbound',endedAt:old,
    durationSeconds:90,outcome:'Positive conversation',nextStep:'Send overview'});
  const proof=recordConfirmedAddress(d,morgan.id,{address:'morgan@customer.example',sourceId:historic.id,detail:'Morgan spelled the address on this call.'});
  const confirmed=crmContactMethod(morgan,'email');
  assert.equal(confirmed.lastCheckedAt,proof.at);
  assert.equal(confirmed.lastVerifiedAt,old);
  assert.match(confirmed.source,/call/);
  assert.equal(crmContactMethod(morgan,'phone').lastCheckedAt,null);

  const added=crmSaveContact(d,{firstName:'Erin',lastName:'Snow',phone:'(505) 555-0101',accountId:'new',company:'Example partner',domain:'example-partner.example',ownerId:sam.ownerId});
  crmRecordMethodCheck(d,added.id,{...confirmPhone,value:added.phone});
  persistContactMethods(d);
  const active=dataset(industry.id),freshSam=active.contacts[0];
  Object.assign(freshSam,{callAllowed:false,emailAllowed:false,queueStatus:'Excluded'});
  const reload=restoreContactMethods(active);
  assert.equal(freshSam.callAllowed,false);
  assert.equal(freshSam.emailAllowed,false);
  assert.equal(freshSam.queueStatus,'Excluded');
  assert.equal(freshSam.email,sam.email);
  assert.equal(freshSam.phone,sam.phone);
  assert.equal(crmContactMethod(freshSam,'phone').lastVerifiedAt,null);
  assert.deepEqual(crmContactMethod(reload.contacts[1],'email'),confirmed);
  const restoredNew=reload.contacts.find(c=>c.id===added.id);
  assert.equal(restoredNew.name,'Erin Snow');
  assert.ok(reload.accounts.some(a=>a.id===restoredNew.accountId&&a.name==='Example partner'));
  assert.equal(crmContactMethod(restoredNew,'phone').status,'Verified');
  assert.ok(reload.salesActivity.some(a=>a.contactMethod==='email'&&a.detail.includes(uncertain.evidence)));
  assert.deepEqual(reload.crmEmails,d.crmEmails);
  assert.ok(reload.nextSalesId>=d.nextSalesId);
  assert.equal(reload.contacts.length,d.contacts.length);
}
storage.clear();
const mailOnly=restoreContactMethods(dataset('agency'));
const existing=mailOnly.contacts[0];
const intro=person=>crmLogInbound(mailOnly,{sender:person.email,subject:'Introduction',body:'My contact details follow.',received:'2026-02-01T08:30Z'});
intro(existing);
persistContactMethods(mailOnly);
assert.equal(restoreContactMethods(dataset('agency')).crmEmails[0].contactId,existing.id);
const added=crmSaveContact(mailOnly,{firstName:'Casey',lastName:'Vale',email:'casey@vale.example',accountId:'new',company:'Vale',domain:'vale.example',ownerId:existing.ownerId});
intro(added);
persistContactMethods(mailOnly);
const untouched=restoreContactMethods(dataset('agency'));
assert.equal(untouched.crmEmails.length,2);
assert.ok(untouched.contacts.some(person=>person.id===added.id));
const same=untouched.contacts[0],receipt=untouched.crmEmails.find(m=>m.contactId===same.id);
const observed=crmRecordMethodCheck(untouched,same.id,{method:'phone',value:same.phone,result:'verified',source:'Direct reply confirming number',evidence:'Confirmed that this is the office line.',checkedAt:'2026-03-03T12:30Z',sourceMessageId:receipt.id});
assert.equal(observed.sourceMessageId,receipt.id);
assert.equal(observed.verificationMessageId,receipt.id);
assert.equal(observed.lastVerifiedAt,receipt.at);
assert.equal(observed.lastCheckedAt,'2026-03-03T12:30:00.000Z');
assert.equal(restoreContactMethods(dataset('events')).crmEmails,undefined);
console.log('PASS contact method checks, legacy evidence, distinct source/check dates, changed values, phone suppression, stale form rejection and scoped session restore across eight industries.');
