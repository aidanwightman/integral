import assert from 'node:assert/strict';
import {dataset,INDUSTRIES} from '../../outputs/workspace-concepts/studio-src/data.js';
import {startCall,connectCall,endCall,logCall,salesEvent,scheduleSalesCall} from '../../outputs/workspace-concepts/studio-src/calling.js';
import {outcomeAction,outcomeSnapshot,followupRecord,recordFollowupReceipt,scheduleFollowupCall,logFollowupCall,resetOutcome} from '../../outputs/workspace-concepts/studio-src/outcomes-model.js';

const minute=Math.floor(Date.now()/60000)*60000;
const earlier=new Date(minute-3600000).toISOString();
const later=new Date(minute+86400000).toISOString();
for(const {id} of INDUSTRIES){
 const d=dataset(id),sam=d.contacts[0],owner=d.team[0].id;
 const read=()=>followupRecord(d);
 assert.equal(read().contactId,sam.id);
 assert.equal(read().accountId,sam.accountId);
 assert.equal(read().canSchedule,true);
 assert.equal(read().messageId,null);
 assert.ok(read().ownerOptions.some(p=>p.value===owner));
 const receipt={channel:'Phone',evidence:'Sam quoted the section about order approvals.'};
 const booking={scheduledAt:later,ownerId:owner,agenda:'Review the approval example with Sam.'};
 assert.throws(()=>recordFollowupReceipt(d,receipt),/Send/);
 assert.throws(()=>scheduleFollowupCall(d,booking),/Send/);
 const began=Date.now();
 outcomeAction(d,'followup','validate',{email:'sam@example.com'});
 const draft=outcomeSnapshot(d,'followup').message;
 outcomeAction(d,'followup','send');
 assert.equal(Date.parse(read().history[0].at),Date.parse('2026-11-17T09:00:00Z'));
 assert.ok(read().history.slice(1).every(h=>Date.parse(h.at)>=began&&Date.parse(h.at)<=Date.now()));
 const tutorialOnly=structuredClone(d);
 assert.equal(outcomeSnapshot(tutorialOnly,'followup').hasFollowupActivity,false);
 resetOutcome(tutorialOnly,'followup');
 assert.equal(followupRecord(tutorialOnly).messageId,null);
 assert.deepEqual(d.outcomePractice.cases.followup.sentMessage,{subject:draft.subject,to:draft.to,body:draft.body});
 const sent=structuredClone(d.outcomePractice.cases.followup.deliveryEvent);
 assert.equal(sam.email,'sam.carter@customer.example');
 assert.throws(()=>recordFollowupReceipt(d,{...receipt,channel:'Provider'}),/how Sam/);
 const r=recordFollowupReceipt(d,receipt);
 assert.equal(outcomeSnapshot(d,'followup').hasFollowupActivity,true);
 const receiptOnly=structuredClone(d);
 assert.equal(receiptOnly.salesActivity[0].relatedId,r.id);
 resetOutcome(receiptOnly,'followup');
 assert.equal(followupRecord(receiptOnly).receipt,null);
 assert.ok(!receiptOnly.salesActivity.some(event=>event.relatedId===r.id));
 assert.deepEqual(recordFollowupReceipt(d,receipt),r);
 assert.throws(()=>recordFollowupReceipt(d,{...receipt,evidence:'Different evidence'}),/already recorded/);
 assert.equal(read().receipt.evidence,receipt.evidence);
 assert.equal(d.outcomePractice.cases.followup.deliveries,0);
 assert.throws(()=>scheduleFollowupCall(d,{...booking,scheduledAt:earlier}),/future/);
 assert.throws(()=>scheduleFollowupCall(d,{...booking,scheduledAt:'2027-02-30T15:00'}),/valid date/);
 const task=scheduleFollowupCall(d,booking),taskCount=d.salesTasks.length;
 assert.equal(task.scheduledAt,later);
 const bookedAt=new Intl.DateTimeFormat('en-GB',{day:'numeric',month:'short',year:'numeric',hour:'2-digit',minute:'2-digit',timeZone:task.timeZone,timeZoneName:'short'}).format(new Date(later));
 assert.ok(read().history.at(-1).detail.includes(bookedAt));
 assert.equal(task.contactId,sam.id);
 assert.equal(scheduleFollowupCall(d,booking).id,task.id);
 assert.equal(d.salesTasks.length,taskCount);
 assert.throws(()=>scheduleFollowupCall(d,{...booking,agenda:'Different agenda'}),/already has a call/);
 assert.throws(()=>scheduleFollowupCall(d,{...booking,ownerId:'outside-team'}),/owner/);
 const completed={endedAt:earlier,ownerId:owner,outcome:'Positive conversation',notes:'Sam will bring his operations lead.',durationSeconds:420,nextStep:'Review sample together.',bookingId:task.id};
 assert.throws(()=>logFollowupCall(d,{...completed,bookingId:d.salesTasks.at(-1).id}),/open booking/);
 assert.throws(()=>logFollowupCall(d,{...completed,endedAt:later}),/past/);
 assert.throws(()=>logFollowupCall(d,{...completed,nextStep:''}),/next step/);
 const logged=logFollowupCall(d,completed);
 assert.equal(logFollowupCall(d,completed).id,logged.id);
 assert.throws(()=>logFollowupCall(d,{...completed,notes:'Other conversation'}),/already logged/);
 assert.equal(read().bookings[0].completedCallId,logged.id);
 assert.equal(read().calls[0].bookingId,task.id);
 assert.equal(d.calls.find(call=>call.id===logged.id).scheduledTaskId,task.id);
 assert.equal(read().history.filter(h=>h.id==='call:'+logged.id).length,1);
 assert.equal(read().bookings[0].status,'Complete');
 assert.equal(d.emailOutbox.length,0);
 assert.equal(d.callJobs.length,0);
 outcomeAction(d,'followup','reconcile');
 const history=read().history;
 assert.ok(Date.parse(history.at(-1).at)>=Date.parse(history.at(-2).at));
 assert.equal(outcomeSnapshot(d,'followup').message.body,draft.body);
 const oldDemo=structuredClone(d);
 delete oldDemo.outcomePractice.cases.followup.sentMessage;
 assert.equal(outcomeSnapshot(oldDemo,'followup').message.body,draft.body);
 const missed=logFollowupCall(d,{endedAt:new Date(minute-1800000).toISOString(),ownerId:owner,outcome:'No answer',notes:'Rang out.'});
 assert.equal(missed.durationSeconds,0);
 const second=scheduleFollowupCall(d,{...booking,scheduledAt:new Date(minute+2*86400000).toISOString()});
 assert.equal(read().bookings.find(b=>b.id===second.id).status,'Open');
 assert.deepEqual(read().receipt,r);
 assert.equal(d.outcomePractice.cases.followup.attempts,1);
 assert.equal(d.outcomePractice.cases.followup.deliveries,1);
 assert.deepEqual(d.outcomePractice.cases.followup.deliveryEvent,sent);
 const copy=JSON.parse(JSON.stringify(d));
 assert.deepEqual(followupRecord(copy),read());
 const projection=read();
 projection.receipt.evidence='Testing copy isolation';
 assert.equal(read().receipt.evidence,receipt.evidence);

 // Complete a linked booking in the dialer so its generated job, email, task and events have to follow the booking.
 const dialed=startCall(d,sam.id,second.id);
 connectCall(d,dialed.id);
 endCall(d,dialed.id);
 const dayThree=new Date(minute+3*86400000);
 const scheduledAt=new Date(dayThree.getTime()-dayThree.getTimezoneOffset()*60000).toISOString().slice(0,16);
 logCall(d,dialed.id,{outcome:'Positive conversation',notes:'Reviewed the overview.',nextStep:'Plan a visit.',scheduledAt,scheduledPurpose:'Follow-up call',scheduledOwnerId:owner});
 const linkedJob=d.callJobs.find(job=>job.callId===dialed.id),linkedEmail=d.emailOutbox.find(email=>email.callId===dialed.id);
 assert.ok(linkedJob&&linkedEmail);
 assert.ok(d.outreach.some(row=>row.id===linkedEmail.id));
 const nextTask=d.salesTasks.find(t=>t.source===dialed.id);
 assert.ok(d.salesActivity.some(e=>e.recordId===sam.id&&e.relatedId===nextTask.id));
 const other=startCall(d,sam.id);
 endCall(d,other.id);
 logCall(d,other.id,{outcome:'No answer',notes:'Unrelated outbound call.'});
 const otherTask=d.salesTasks.find(t=>t.source===other.id);
 const separateBooking=scheduleSalesCall(d,sam.id,{scheduledAt,purpose:'Setup call',ownerId:d.team[1].id,agenda:'Separate project.'});
 salesEvent(d,'Contact reviewed',sam.id,'Separate account review.');
 const unrelatedEvent=d.salesActivity[0].id;
 logFollowupCall(d,{endedAt:new Date(minute-1200000).toISOString(),ownerId:owner,outcome:'Do not contact',notes:'Sam opted out of calls and email.',durationSeconds:45});
 resetOutcome(d,'followup');
 assert.equal(outcomeSnapshot(d,'followup').stage,0);
 assert.equal(outcomeSnapshot(d,'followup').hasFollowupActivity,false);
 assert.equal(read().receipt,null);
 assert.deepEqual(read().bookings,[]);
 assert.deepEqual(read().calls,[]);
 assert.equal(read().history.length,1);
 assert.equal(sam.callAllowed,false);
 assert.equal(sam.emailAllowed,false);
 assert.equal(sam.queueStatus,'Excluded');
 assert.equal(read().canSchedule,false);
 assert.deepEqual(d.calls.map(call=>call.id),[other.id]);
 assert.ok(d.salesTasks.includes(otherTask));
 assert.ok(d.salesTasks.includes(separateBooking));
 assert.ok(d.salesTasks.every(t=>![task.id,second.id].includes(t.id)&&t.source!==dialed.id));
 assert.ok(!d.callJobs.includes(linkedJob)&&!d.emailOutbox.includes(linkedEmail)&&!d.outreach.some(row=>row.id===linkedEmail.id));
 assert.ok(d.salesActivity.some(event=>event.id===unrelatedEvent));
 assert.ok(d.salesActivity.some(event=>event.recordId===other.id));
 assert.ok(d.salesActivity.some(event=>event.relatedId===separateBooking.id));
 assert.ok(!d.salesActivity.some(event=>event.relatedId===nextTask.id));
 assert.ok(d.salesActivity.every(event=>!event.followupMessageId&&![dialed.id,linkedJob.id,linkedEmail.id,logged.id,missed.id].includes(event.recordId)));
 assert.ok(d.activity.some(event=>event.recordId===other.id));
 assert.ok(!d.activity.some(event=>[dialed.id,logged.id,missed.id].includes(event.recordId)));
}
console.log('PASS linked follow-up receipt, native calls, independent delivery, retries, real timestamps and reset scope across eight datasets.');
