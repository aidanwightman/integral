import assert from 'node:assert/strict';
import {dataset} from '../../outputs/workspace-concepts/studio-src/data.js';
import {crmSaveContact,crmReviewContact,crmReadInbound,crmLogInbound,crmSendEmail,crmBeginDraft,crmSaveDraft,crmSendDraft} from '../../outputs/workspace-concepts/studio-src/contact-model.js';
import {saveContactEmail,logCompletedCall,addCallNote} from '../../outputs/workspace-concepts/studio-src/calling.js';

const data=dataset('agency');
const entry={firstName:'Avery',lastName:'Rai',ownerId:data.team[0].id,accountId:'new',company:'Northline Studio',domain:'northline.example',email:'  AVERY@northline.example ',phone:'+44 7700 900044',title:'Operations director',emailAllowed:false,source:'Incoming email'};
const initialAccounts=data.accounts.length, initialPeople=data.contacts.length;
assert.throws(()=>crmSaveContact(data,{...entry,email:'missing-at'}));
assert.equal(data.accounts.length,initialAccounts);
const contact=crmSaveContact(data,entry);
assert.equal(data.accounts.length,initialAccounts+1);
assert.equal(data.contacts.length,initialPeople+1);
assert.equal(contact.email,'avery@northline.example');
assert.equal(data.accounts.find(a=>a.id===contact.accountId).domain,'northline.example');
assert.throws(()=>crmSaveContact(data,{...entry,company:'Northline Holdings'}),/existing company/);
const existingCompany={...entry,accountId:contact.accountId};
const exactMatch=crmReviewContact(data,{...existingCompany,email:entry.email.toUpperCase()}).matches;
assert.equal(exactMatch.length,1);
assert.equal(exactMatch[0].exact,true);
assert.throws(()=>crmSaveContact(data,existingCompany,{reviewed:true}),/matching records/);
const namesake={...existingCompany,email:'another.avery@northline.example',phone:''};
assert.equal(crmReviewContact(data,namesake).matches[0].exact,false);
assert.throws(()=>crmSaveContact(data,namesake),/matching records/);
const other=crmSaveContact(data,namesake,{reviewed:true});
assert.notEqual(other.id,contact.id);
assert.throws(()=>saveContactEmail(data,other.id,contact.email.toUpperCase()),/another contact/);
const inbound={sender:entry.email,subject:'A delivery question',body:'Who owns the reporting handoff?',received:'2026-11-16T09:30',messageId:'brief-001@northline.example'};
assert.equal(crmReadInbound(data,{...inbound,sender:'unseen@northline.example'}).contact,undefined);
assert.throws(()=>crmLogInbound(data,{...inbound,sender:'unseen@northline.example'}),/contact record/);
assert.equal(crmLogInbound(data,inbound).contactId,contact.id);
assert.equal(crmLogInbound(data,inbound).duplicate,true);
assert.equal(crmLogInbound(data,{...inbound,messageId:''}).duplicate,true);
assert.throws(()=>crmLogInbound(data,{...inbound,body:'Different payload'}),/different email/);
assert.equal(data.crmEmails.length,1);
assert.equal(data.crmEmails[0].accountId,contact.accountId);
assert.throws(()=>crmSendEmail(data,contact.id,{subject:'Reply',body:'Yes'}),/disabled/);
const totalBeforeEdit=data.contacts.length;
crmSaveContact(data,{...existingCompany,title:'VP Operations',emailAllowed:true},{editingId:contact.id,reviewed:true});
assert.equal(data.contacts.length,totalBeforeEdit);
assert.equal(contact.title,'VP Operations');
assert.equal(contact.emailAllowed,true);
assert.throws(()=>crmSendEmail(data,contact.id,{subject:'',body:'Reply'}),/subject/);
const email=crmSendEmail(data,contact.id,{subject:'Re: A delivery question',body:'Here is the reporting plan.'});
assert.equal(email.address,contact.email);
assert.equal(data.crmEmails.length,2);
assert.equal(data.activity[0].accountId,contact.accountId);
assert.equal(data.activity[0].recordId,contact.id);
assert.equal(data.salesActivity[0].recordId,contact.id);
console.log('PASS: contact/company matching, duplicate reviews, inbound matching and idempotence, outbound preferences and linked timelines.');

const noAddress = data.contacts[1];
const opportunity = data.opportunities.find(row=>row.accountId===noAddress.accountId);
const {call} = logCompletedCall(data,{contactId:noAddress.id,ownerId:data.team[0].id,direction:'Inbound',endedAt:'2025-04-10T09:00',durationSeconds:120,outcome:'Callback requested',notes:'Internal cost ceiling.',nextStep:'Share a proposal on Friday',opportunityId:opportunity.id});
const noteValues = {contactId:noAddress.id, authorId:data.team[1].id, kind:'Correction', body:'The call was with the purchasing team.', revision:0};
const note = addCallNote(data,call.id,noteValues);
assert.equal(addCallNote(data,call.id,noteValues),note);
assert.equal(call.addenda.length,1);
assert.equal(call.notes,'Internal cost ceiling.');
assert.equal(data.activity[0].opportunityId,opportunity.id);
assert.equal(note.author,data.team[1].name);
assert.ok(Number.isFinite(Date.parse(note.at)));
assert.throws(()=>addCallNote(data,call.id,{...noteValues,body:'A stale edit.'}),/newer notes/);
assert.throws(()=>addCallNote(data,call.id,{...noteValues,contactId:contact.id}),/completed call/);

const followUp = crmBeginDraft(data,noAddress.id,{callId:call.id});
assert.match(followUp.body,/Share a proposal on Friday/);
assert.doesNotMatch(followUp.body,/cost ceiling|purchasing team/);
const firstSaved = crmSaveDraft(data,followUp);
assert.equal(crmSaveDraft(data,followUp).version,1);
assert.equal(data.crmDrafts.length,1);
assert.equal(data.activity.filter(item=>item.action==='Email draft saved').length,1);
assert.throws(()=>crmSendDraft(data,firstSaved),/recipient/);
const revised = crmSaveDraft(data,{...firstSaved,body:'Here is the updated proposal.'});
assert.throws(()=>crmSaveDraft(data,{...firstSaved,body:'Older edit'}),/changed/);
assert.equal(data.crmDrafts[0].body,revised.body);
saveContactEmail(data,noAddress.id,'confirmed@juniperworks.example');
assert.throws(()=>crmSendDraft(data,revised),/recipient/);
const reviewed = {...revised,address:noAddress.email};
noAddress.emailAllowed=false;
assert.throws(()=>crmSendDraft(data,reviewed),/disabled/);
assert.equal(data.crmDrafts.length,1);
noAddress.emailAllowed=true;
const delivered = crmSendDraft(data,reviewed);
assert.equal(crmSendDraft(data,reviewed).id,delivered.id);
assert.equal(data.crmDrafts.length,0);
assert.equal(delivered.callId,call.id);
assert.throws(()=>crmSaveDraft(data,reviewed),/already been sent/);

const source = data.crmEmails.find(row=>row.direction==='Incoming');
assert.throws(()=>crmBeginDraft(data,noAddress.id,{replyToId:source.id}),/incoming/);
const replyDraft = crmBeginDraft(data,contact.id,{replyToId:source.id});
assert.equal(replyDraft.subject,'Re: '+source.subject);
replyDraft.body='We can send the first draft tomorrow.';
const readyReply=crmSaveDraft(data,replyDraft);
const oldAddress=contact.email;
contact.email='new@northline.example';
assert.throws(()=>crmSendDraft(data,{...readyReply,address:contact.email}),/original sender/);
contact.email=oldAddress;
const reply=crmSendDraft(data,readyReply);
assert.equal(reply.threadId,source.id);
assert.equal(reply.replyToId,source.id);
console.log('PASS: attributed call addenda, repeat-safe amendments, private note isolation, saved and stale drafts, reviewed recipient changes, consent checks, linked replies and repeat-safe send.');
