import assert from 'node:assert/strict';
import {contactWorkspace} from '../../outputs/workspace-concepts/studio-src/contact-workspace.js';
import {dataset} from '../../outputs/workspace-concepts/studio-src/data.js';
import {researchContactEmail,contactEmailResearch} from '../../outputs/workspace-concepts/studio-src/email-research.js';
import {startCall,connectCall,endCall,logCall} from '../../outputs/workspace-concepts/studio-src/calling.js';

const d=dataset('agency'), target=d.contacts[1];
const lookup=()=>researchContactEmail(d,target);
const blankRecord = contactWorkspace(d,{callContact:target.id});
assert.match(blankRecord,/data-email-entry/);
assert.match(blankRecord,/data-open-email-lookup[^>]*aria-haspopup="dialog"/);
assert.doesNotMatch(blankRecord,/Inspect 26 source records|class="email-research-group"|morgan.quinn@juniperworks.example/);
const savedRecord = contactWorkspace(d,{callContact:d.contacts[0].id});
assert.doesNotMatch(savedRecord,/data-open-email-lookup|class="email-research-group"/);
assert.match(savedRecord,/data-saved-email/);

const initial=lookup(), candidate=initial.candidate;
assert.equal(initial.peers.length,7);
assert.equal(candidate,'morgan.quinn@juniperworks.example');
assert.equal(target.email,'');
const call=startCall(d,target.id);
connectCall(d,call.id);
call.connectedAt=new Date(Date.now()-65000).toISOString();
endCall(d,call.id);
assert.ok(call.durationSeconds>=65);
const deal=d.opportunities.find(o=>o.accountId===target.accountId);
assert.throws(()=>logCall(d,call.id,{outcome:'Positive conversation',nextStep:'Demo',opportunityId:'another-company'}));
assert.equal(call.status,'Wrap-up');
logCall(d,call.id,{outcome:'Positive conversation',notes:'Budget agreed.',nextStep:'Agree the scope',opportunityId:deal.id,callbackDate:'2026-11-23'});
assert.equal(call.opportunityId,deal.id);
assert.ok(d.activity.some(a=>a.recordId===call.id && a.accountId===target.accountId));
assert.equal(d.callJobs[0].status,'Waiting for email');
assert.equal(d.emailOutbox.length,0);

const junior = d.contacts.find(c => c.name === 'Jamie Rivers');
const forJunior = researchContactEmail(d,junior);
assert.equal(forJunior.candidate,'jrivers@juniperworks.example');
assert.equal(forJunior.peers.length,26);
assert.equal(forJunior.matched,25);
assert.equal(forJunior.groups.leadership.count,7);
assert.equal(researchContactEmail(d,target,'junior').candidate,'mquinn@juniperworks.example');
assert.equal(researchContactEmail(d,junior,'leadership').candidate,'jamie.rivers@juniperworks.example');
assert.equal(researchContactEmail(d,{...target,title:'Consultant'}).candidate,undefined);
assert.equal(researchContactEmail(d,{...target,title:'Assistant to the CEO'}).roleGroup,null);
assert.equal(researchContactEmail(d,{...target,title:'Graduate account executive'}).group,'junior');
assert.equal(researchContactEmail(d,{...target,name:'Morgan de Groot'}).candidate,undefined);
assert.equal(researchContactEmail(d,{...target,name:'Núria Quinn'}).candidate,undefined);
assert.equal(researchContactEmail(d,{...target,name:'Harper Lake Mathers',firstName:'Harper',lastName:'Mathers'}).candidate,'harper.mathers@juniperworks.example');

const peer=initial.peers[0], original=peer.email;
peer.email='ada.frost@other.example'; assert.equal(lookup().candidate,undefined);
peer.email='sales@juniperworks.example'; assert.equal(lookup().candidate,undefined);
const duplicateLeader={...initial.peers[1],id:'nia-alias',email:'npatel@juniperworks.example'};
d.contacts.push(duplicateLeader); assert.equal(lookup().peers.length,5);
d.contacts.pop();
peer.email=original;
d.contacts.push({...peer,id:'repeat-id'});assert.equal(lookup().peers.length,7);d.contacts.pop();
d.contacts.push({...peer,name:'Someone Else',email:peer.email,id:'shared-id'});assert.equal(lookup().peers.length,6);d.contacts.pop();
peer.emailStatus='inferred';assert.equal(lookup().peers.length,6);delete peer.emailStatus;
peer.email='ada.frost+news@juniperworks.example';assert.equal(lookup().peers.length,6);peer.email=original;
d.contacts.push({...d.contacts[0],id:'conflict',email:candidate});assert.match(lookup().message,/already saved/);
d.contacts.pop();
d.contacts[0].emailAliases=[candidate];assert.match(lookup().message,/already saved/);delete d.contacts[0].emailAliases;
const second=d.contacts[0];assert.equal(researchContactEmail(d,second).address,second.email);
d.contacts.push({...target,id:'same-person',email:'mquinn@juniperworks.example'});assert.match(lookup().message,/same-name/);
d.contacts.pop();
const importedGuess = {...target,email:candidate,emailStatus:'inferred'};
assert.equal(researchContactEmail(d,importedGuess).address,undefined);
assert.equal(researchContactEmail(d,importedGuess).candidate,candidate);
assert.match(contactEmailResearch(d,importedGuess),/Current entry requires review/);
assert.equal(researchContactEmail(d,{...importedGuess,emailStatus:'bounced'}).candidate,undefined);
const refs=lookup().peers;
for (const c of refs.slice(0,4)) c.email=c.firstName.toLowerCase()[0]+c.lastName.toLowerCase()+'@juniperworks.example';
assert.equal(lookup().candidate,undefined,'A 4–3 split is weak evidence');
for (const c of refs.slice(4,6)) c.email=c.firstName.toLowerCase()[0]+c.lastName.toLowerCase()+'@juniperworks.example';
assert.equal(lookup().candidate,'mquinn@juniperworks.example');
assert.equal(researchContactEmail(d,{...target,title:'Consultant'}).candidate,'mquinn@juniperworks.example');
assert.equal(junior.email,'');
assert.equal(target.email,'');
assert.equal(d.emailOutbox.length,0);
const unknown=contactEmailResearch(dataset('agency'),{...target,title:'Consultant'});
assert.equal((unknown.match(/email-group-[^"]+" open>/g)||[]).length,0);
assert.match(unknown,/Review the groups separately/);
console.log('PASS: saved addresses, 7 vs 26 colleagues, exceptions, evidence thresholds, title conflicts, alias and domain isolation, call association and no sends to guesses.');
